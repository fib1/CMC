/* ---------------------------------------------------------------
   下面是让「每日」内容当天固定的小工具，一般不用改
   --------------------------------------------------------------- */

const todayKey = () => {
  const d = new Date();
  return `${d.getFullYear()}-${d.getMonth() + 1}-${d.getDate()}`;
};

/** 简单稳定的字符串哈希 */
function hash(str: string) {
  let h = 2166136261;
  for (let i = 0; i < str.length; i++) {
    h ^= str.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}

/** 当天固定的一条（同一天刷新多少次都一样，第二天自动换） */
export function pickDaily<T>(list: T[], salt: string): T {
  return list[hash(todayKey() + salt) % list.length];
}

/** 随机一条，尽量不和上一条重复 */
export function pickRandom<T>(list: T[], exclude?: T): T {
  if (list.length <= 1) return list[0];
  let item = list[Math.floor(Math.random() * list.length)];
  let guard = 0;
  while (item === exclude && guard++ < 8) {
    item = list[Math.floor(Math.random() * list.length)];
  }
  return item;
}

/** 根据当前时间挑一句问候 */
export function pickGreeting() {
  const h = new Date().getHours();
  const pool =
    h < 5 ? greetings.lateNight
    : h < 11 ? greetings.morning
    : h < 14 ? greetings.noon
    : h < 18 ? greetings.afternoon
    : h < 23 ? greetings.evening
    : greetings.lateNight;
  return pickRandom(pool);
}
